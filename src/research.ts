import {
  cool,
  createState,
  separate,
  percent,
  mass,
  inventoryMass,
  rock,
  chamber,
} from "./engine";
import { sameState, verifyRun, witnesses } from "./experiments";
import { oxides, modelVersion } from "./data";
import type { RecordEntry } from "./storage";

export type ResearchBoard = {
  textureA?: string;
  textureB?: string;
  retained?: string;
  separated?: string;
  candidate?: string;
};
export const evidenceSlots: { key: keyof ResearchBoard; label: string }[] = [
  { key: "textureA", label: "结构证词 · 样品一" },
  { key: "textureB", label: "结构证词 · 样品二" },
  { key: "retained", label: "分离证词 · 保留晶体" },
  { key: "separated", label: "分离证词 · 移走晶体" },
  { key: "candidate", label: "与未知报告相容的液相" },
];
// The report is generated by this engine. Ranges are puzzle tolerances, not measurement uncertainty.
const reference = cool(
  separate(separate(cool(createState(), 1100), "olivine", 1), "pyroxene", 1),
  1000,
);
const ref = percent(reference.liquid);
export const researchTarget = {
  source: "教学合成分析",
  modelVersion,
  temperature: 1000,
  SiO2: { min: ref.SiO2 - 0.35, max: ref.SiO2 + 0.35 },
  CaO: { min: ref.CaO - 0.45, max: ref.CaO + 0.45 },
};
export function evaluateResearch(board: ResearchBoard, records: RecordEntry[]) {
  const get = (key: keyof ResearchBoard) =>
    records.find((r) => r.id === board[key]);
  const a = get("textureA"),
    b = get("textureB"),
    r = get("retained"),
    s = get("separated"),
    c = get("candidate");
  const verified = (x?: RecordEntry) => !!x?.run && verifyRun(x.run, x.state);
  const noRemoval = (x: RecordEntry) => inventoryMass(x.state.removed) < 1e-8;
  const checks = [
    {
      id: "texture",
      passed: false,
      text: "提交两份同源、同终温的岩石记录，只改变快慢冷。",
    },
    {
      id: "transfer",
      passed: false,
      text: "提交保留与分离的液相记录；操作日志会自动核对分离瞬间。",
    },
    {
      id: "evolution",
      passed: false,
      text: "分离后继续冷却，在同温度比较液相。",
    },
    {
      id: "candidate",
      passed: false,
      text: "提交符合未知报告两项组成范围的液相记录。",
    },
  ];
  if (a && b) {
    const ok =
      verified(a) &&
      verified(b) &&
      a.kind === "chamber" &&
      b.kind === "chamber" &&
      sameState(a.run!.initial, b.run!.initial) &&
      noRemoval(a) &&
      noRemoval(b) &&
      a.state.temperature === 650 &&
      b.state.temperature === 650 &&
      rock(a.state).texture !== rock(b.state).texture &&
      oxides.every(
        (o) => Math.abs(chamber(a.state)[o] - chamber(b.state)[o]) < 1e-8,
      );
    checks[0] = {
      id: "texture",
      passed: ok,
      text: ok
        ? "结构不同，总体化学相同：冷却速度没有创造元素。"
        : "需要可重放的同起点岩石，两份都到650°C、无分离，且一粗一细。",
    };
  }
  if (r && s) {
    const verifiedPair = verified(r) && verified(s);
    const common =
      verifiedPair &&
      r.kind === "liquid" &&
      s.kind === "liquid" &&
      sameState(r.run!.initial, s.run!.initial) &&
      noRemoval(r);
    const ws = verifiedPair ? witnesses(s.run!) : [];
    const transfer =
      common &&
      ws.some(
        (w) =>
          inventoryMass(w.after.removed) - inventoryMass(w.before.removed) >
            1e-8 &&
          oxides.every(
            (o) => Math.abs(w.after.liquid[o] - w.before.liquid[o]) < 1e-8,
          ),
      );
    checks[1] = {
      id: "transfer",
      passed: transfer,
      text: transfer
        ? "重放确认：已有晶体进入堆晶库存，分离瞬间液相没有变化。"
        : "需要同一起点的两份液相记录，其中一条保留全部晶体，另一条实际分离了晶体。",
    };
    const diff = Math.abs(
      percent(r.state.liquid).SiO2 - percent(s.state.liquid).SiO2,
    );
    const sameT = r.state.temperature === s.state.temperature;
    const evolved =
      transfer &&
      sameT &&
      ws.some((w) => w.continuedCooling) &&
      mass(r.state.liquid) > 1 &&
      mass(s.state.liquid) > 1 &&
      diff >= 0.2;
    checks[2] = {
      id: "evolution",
      passed: evolved,
      text: evolved
        ? `同温度液相 SiO₂ 相差 ${diff.toFixed(3)} 个百分点；后续历史产生了差异。`
        : !sameT
          ? "温度不同，先在同温度比较，才能隔离分离历史的影响。"
          : "分离只搬走固体。继续冷却，再观察液相差异是否达到0.2个百分点。",
    };
  }
  if (c) {
    const p = percent(c.state.liquid);
    const ok =
      verified(c) &&
      c.kind === "liquid" &&
      mass(c.state.liquid) > 1 &&
      c.state.temperature === researchTarget.temperature &&
      p.SiO2 >= researchTarget.SiO2.min &&
      p.SiO2 <= researchTarget.SiO2.max &&
      p.CaO >= researchTarget.CaO.min &&
      p.CaO <= researchTarget.CaO.max;
    checks[3] = {
      id: "candidate",
      passed: ok,
      text: ok
        ? "这条可重放路径与报告相容，仍不能排除其他形成过程。"
        : "候选必须是1000°C液相，并同时符合SiO₂与CaO范围；保留这次结果，调整一个变量再试。",
    };
  }
  return {
    passed: checks.every((x) => x.passed),
    checks,
    text: checks.every((x) => x.passed)
      ? "证据成立：找到一种可能的历史。我们没有给未知样品补办唯一身份证。"
      : `已验证 ${checks.filter((x) => x.passed).length}/4 项证据。记录不会因未达标而丢失。`,
  };
}
